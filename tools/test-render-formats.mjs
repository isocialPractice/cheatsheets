// The output surface, pinned against committed output - one render per format.
//
// `tools/test-render-fixture.mjs` beside this pins the layer **below**: a
// composition at a named seed, as SVG in full and as a raster digest. Every
// case here goes through `api/cheatsheet/render.mjs` instead, which is the door
// a caller actually uses, and asks a different question of each format: not
// *did the composition move* but *did the surface change what it made of it*.
//
// Both matter, and the gap between them is where this file lives. Until it
// landed, the five formats were covered by property checks - a fragment has no
// XML declaration, a raster says which route drew it, a format nobody renders
// is refused by name - every one of which would still pass if the fragment
// gained a stray attribute, the scaling rules changed shape, or a media type
// were corrected to something plausible and wrong. Nothing in the repository
// said what the surface's output was supposed to *be*.
//
// ## What is pinned, and in what form
//
// | Format | Pinned as | Needs |
// | --- | --- | --- |
// | `svg` | `fixtures/sheet.svg`, byte for byte | Nothing |
// | `html` | `fixtures/sheet.fragment.html`, in full | Nothing |
// | `png` | `fixtures/sheet.png.sha256`, by digest | Nothing |
// | `jpeg` | The declared surface only | A browser |
// | `webp` | The declared surface only | A browser |
//
// Two of those files are the ones `test-render-fixture.mjs` already commits,
// and reusing them is deliberate rather than thrift. The claim worth pinning
// about `svg` is that **the surface adds nothing**: `renderSheet(doc, { format:
// "svg" })` is the composition's own markup, so a second copy of 80 KB would
// not say anything the equality does not, and would be a second thing to
// regenerate. The same holds for `png` at the built-in route and scale 1, which
// is `composition.toPNG()` reached through the door.
//
// ## Why the two browser formats pin no bytes
//
// They cannot be rendered at all without Chromium, so on a bare clone there is
// nothing to compare and the cases skip with the install command as their
// reason - the pattern `tools/test-sheet-raster.mjs` settled. That is the
// requirement rather than a shortfall: the suite has to run on a clone with
// nothing installed.
//
// But the bytes would not be pinned even with an engine present, and that is
// the more interesting half. A browser raster is the engine's output in the
// face it resolved, so its bytes move with the Chromium build, the platform's
// font stack and the codec's own version - none of which is this repository's
// change. A digest over them would fail on somebody else's release schedule,
// which is the failure that teaches a person to regenerate without reading.
// What is pinned instead is the part that is this repository's: the media type,
// the extension, the filename derived from the title, and the pixel dimensions
// the named scale asks for.
//
// ## Regenerating
//
// A deliberate change to the surface will fail these cases, and that is the
// point: the failure is the review. Once the new output has been looked at:
//
//   MCP_FIXTURE_UPDATE=1 node --test tools/test-render-formats.mjs
//
// The same switch regenerates `test-render-fixture.mjs`'s files, so a change
// that moves the composition is regenerated by running both - or by running the
// suite with the switch set, which is the form to prefer when a change reaches
// the composition and the surface at once.
//
// Run with: node --test tools/test-render-formats.mjs
import { test } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  composeSheet,
  filenameFor,
  renderFragment,
  renderOf,
  renderSVG,
  renderSheet,
  RASTER_RENDERS,
  RENDER_EXTENSIONS,
  RENDER_FORMATS,
  RENDER_MEDIA_TYPES,
} from "../api/cheatsheet/index.mjs";
import { MIN_PUBLISH_SCALE, resolveChromium } from "../api/cheatsheet/raster.mjs";
import { fixtureDocument, FIXTURE_SEED } from "./fixtures/sheet.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fixtures = join(root, "tools", "fixtures");
const update = process.env.MCP_FIXTURE_UPDATE === "1";

/**
 * The scale the two browser formats are rendered at: the publish floor itself.
 *
 * Small on purpose - none of these cases is about resolution, and an engine
 * encoding a 3600 square twice is most of a minute of a suite that runs in
 * twenty seconds. Taken from the constant rather than typed in as a figure
 * below it, because `publishable` is one of the fields being pinned and the
 * floor is what decides it: the smallest render the route may publish is the
 * one worth asking the question of, and a number written here would be a second
 * copy of a measurement that can disagree with the first.
 */
const BROWSER_SCALE = MIN_PUBLISH_SCALE;

const runtime = await resolveChromium();
const skip = runtime.chromium ? false : runtime.reason;

/** @param {Uint8Array} bytes */
function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

/**
 * Compares against a committed file, or writes it when regenerating.
 *
 * The same helper `tools/test-render-fixture.mjs` carries, and deliberately a
 * second copy of it rather than an import: it is nine lines, and a shared one
 * would make `tools/fixtures/` a module two test files depend on for their
 * mechanism as well as their data.
 *
 * @param {string} name
 * @param {string} actual
 * @param {string} why What a mismatch means, for the failure message.
 */
function pinned(name, actual, why) {
  const path = join(fixtures, name);
  if (update) {
    writeFileSync(path, actual);
    return;
  }
  assert.ok(
    existsSync(path),
    `tools/fixtures/${name} is missing. Run MCP_FIXTURE_UPDATE=1 node --test tools/test-render-formats.mjs`
  );
  assert.equal(actual, readFileSync(path, "utf8"), why);
}

/**
 * The composition every case below renders, made once.
 *
 * `renderOf` takes the pair rather than the document for exactly this reason:
 * composing is the expensive half, and this file renders one sheet five times.
 *
 * @type {{ composition: any, variation: any }}
 */
const composed = composeSheet(fixtureDocument(), { seed: FIXTURE_SEED });

/**
 * A render's report with the two halves that are not output stripped out.
 *
 * `variation` and `composition` are on the result so a caller need not hold the
 * pair separately, and neither is this file's to pin: the variation has a
 * fixture of its own in `fixtures/sheet.variation.json`, and a composition is
 * an object graph. `data` and `text` are the bytes, pinned as files above.
 *
 * @param {import('../api/cheatsheet/render.mjs').SheetRender} render
 * @returns {object}
 */
function reportOf(render) {
  const { data, text, variation, composition, ...rest } = render;
  return { ...rest, filename: filenameFor(render) };
}

// --- The three that need nothing installed ----------------------------------

test("the svg format is the composition's own markup, which is what it claims", async () => {
  // Not a copy of the markup but the identity: the surface's job for `svg` is
  // to carry it out with a report around it, so the pin is that the bytes it
  // hands over are the ones the composition made and the file already holds.
  const render = await renderSheet(fixtureDocument(), { seed: FIXTURE_SEED, format: "svg" });
  const committed = readFileSync(join(fixtures, "sheet.svg"), "utf8");
  assert.equal(
    render.text,
    committed,
    "the svg format produced different markup than tools/fixtures/sheet.svg. " +
      "That file is committed by tools/test-render-fixture.mjs, so a failure " +
      "here with that file's own case passing means the surface changed the " +
      "markup on its way out rather than the composition moving."
  );
  // And the three doors onto it agree, which is what stops one of them growing
  // a transform the other two do not have.
  assert.equal(renderSVG(fixtureDocument(), { seed: FIXTURE_SEED }), committed);
  assert.equal((await renderOf(composed, { format: "svg" })).text, committed);
});

test("the html format is the fragment that was committed, in full", async () => {
  const render = await renderSheet(fixtureDocument(), { seed: FIXTURE_SEED, format: "html" });
  pinned(
    "sheet.fragment.html",
    `${render.text}\n`,
    "the fragment changed. This is the case that fails when the declaration, " +
      "the size attributes, the inline scaling rules or the wrapper's class " +
      "move - each of which a page reads, and none of which any property check " +
      "would notice the shape of. Read the diff before regenerating."
  );
  // `renderFragment` is the same transform reached without naming a format, so
  // the two doors have to agree to the character.
  assert.equal(renderFragment(fixtureDocument(), { seed: FIXTURE_SEED }), render.text);
});

test("the png format at the built-in route is the raster that was committed", async () => {
  // Scale 1 and the built-in route on purpose: that is `composition.toPNG()`
  // reached through the surface, so the committed digest covers both and the
  // equality is the claim that the door adds nothing to the bytes.
  const render = await renderOf(composed, { format: "png", route: "builtin" });
  assert.equal(render.scale, 1);
  const record = `${digest(render.data)} ${render.bytes} ${render.pixels.width}x${render.pixels.height}\n`;
  const committed = readFileSync(join(fixtures, "sheet.png.sha256"), "utf8");
  assert.equal(
    record,
    committed,
    "the png format produced a different raster than tools/fixtures/sheet.png.sha256, " +
      "which tools/test-render-fixture.mjs commits from composition.toPNG(). A " +
      "failure here alone means the surface changed the pixels on the way out."
  );
});

test("and the report each of the three hands back is the one that was committed", async () => {
  // The other half of an output surface, and the half a byte comparison says
  // nothing about: a caller embedding a sheet reads the media type, the
  // extension, the route and `publishable` off the result and never looks at
  // the bytes at all. A media type corrected to something plausible and wrong
  // would pass every case above.
  const rows = {};
  for (const format of ["svg", "html"]) {
    rows[format] = reportOf(await renderOf(composed, { format }));
  }
  rows.png = reportOf(await renderOf(composed, { format: "png", route: "builtin" }));
  pinned(
    "sheet.renders.json",
    `${JSON.stringify(rows, null, 2)}\n`,
    "a render's report changed for the fixture document. Every field in it is " +
      "something a caller branches on, so read which one moved before regenerating."
  );
});

// --- The declared surface, which holds for all five -------------------------

test("every format the surface names declares a media type, an extension and a filename", () => {
  // Pinned for the two browser formats as well, because it is the part of their
  // output that is this repository's rather than the engine's - and the part a
  // consumer writing a response header or a file reads without rendering
  // anything.
  const declared = RENDER_FORMATS.map((format) => ({
    format,
    mediaType: RENDER_MEDIA_TYPES[format],
    extension: RENDER_EXTENSIONS[format],
    raster: RASTER_RENDERS.includes(format),
    // The name a caller writing into a directory gets, derived from the title
    // rather than from the format - which is the whole of what `filenameFor`
    // is for, and the one of these four that could change without anybody
    // editing a constant.
    filename: filenameFor({ format, title: "Splicing Array Elements" }),
  }));
  pinned(
    "sheet.formats.json",
    `${JSON.stringify(declared, null, 2)}\n`,
    "the surface's declared formats changed. A media type or an extension " +
      "moving is a change every consumer of this surface sees, whether or not " +
      "it renders anything."
  );
});

// --- The two that need a browser --------------------------------------------

test("the two browser formats render to the pixels the named scale asks for", { skip }, async () => {
  // No digest, per **Why the two browser formats pin no bytes** above: these
  // bytes are the engine's and move with its build, its platform font stack and
  // its codec. What is asserted is the surface's own half of the answer, which
  // does not.
  const committed = JSON.parse(readFileSync(join(fixtures, "sheet.formats.json"), "utf8"));
  const edge = Math.round(composed.composition.toDocument().width * BROWSER_SCALE);
  for (const format of ["jpeg", "webp"]) {
    const render = await renderOf(composed, { format, route: "browser", scale: BROWSER_SCALE });
    const declared = committed.find((row) => row.format === format);
    assert.equal(render.format, format);
    assert.equal(render.mediaType, declared.mediaType);
    assert.equal(render.extension, declared.extension);
    assert.equal(filenameFor(render), declared.filename);
    assert.deepEqual(render.pixels, { width: edge, height: edge }, `${format} did not honour the scale`);
    assert.equal(render.scale, BROWSER_SCALE);
    assert.equal(render.route, "browser");
    // The one field the whole route exists for: a real engine in the face the
    // design language measured is the only render anybody may publish.
    assert.equal(render.publishable, true);
    assert.equal(typeof render.family.resolved, "string");
    assert.ok(render.bytes > 0);
    // Markup is text and a raster is not, which is how a caller tells without
    // consulting the format.
    assert.equal(render.text, null);
  }
});

test("and a bare clone says why it could not compare them rather than failing", () => {
  // The case that runs everywhere, and the one that keeps the two above from
  // being a silent gap. A skipped case reports a reason; nothing reports the
  // absence of one, so this asserts that the reason exists and names the
  // install, on a machine with an engine as readily as on one without.
  if (runtime.chromium) {
    assert.equal(skip, false);
    assert.ok(runtime.chromium, "an engine resolved without a handle to it");
    return;
  }
  assert.equal(typeof skip, "string");
  assert.match(skip, /playwright/i, "the skip reason does not name what to install");
  // And the formats are still declared, which is what the case above compares
  // against and what a consumer reads without rendering.
  for (const format of ["jpeg", "webp"]) {
    assert.ok(RASTER_RENDERS.includes(format));
    assert.equal(typeof RENDER_MEDIA_TYPES[format], "string");
  }
});

// --- What the pinning is worth ----------------------------------------------

test("there is a committed expectation for every format the surface renders", () => {
  // The invariant that keeps this file honest as the surface grows. A sixth
  // format added to `RENDER_FORMATS` has to arrive with a pin or a stated
  // reason it has none, and without this case it would arrive with neither and
  // the suite would report five formats covered out of six.
  const byBytes = ["svg", "html", "png"];
  const byDeclaration = ["jpeg", "webp"];
  assert.deepEqual(
    [...byBytes, ...byDeclaration].sort(),
    [...RENDER_FORMATS].sort(),
    "a format was added to or removed from the surface without this file following it"
  );
  for (const name of ["sheet.svg", "sheet.fragment.html", "sheet.png.sha256", "sheet.renders.json", "sheet.formats.json"]) {
    assert.ok(existsSync(join(fixtures, name)), `tools/fixtures/${name} is not committed`);
  }
});
